#!/usr/bin/env python3
"""Regenerate NOTICE and THIRD-PARTY-NOTICES.md for what a release ships (docs/RELEASING.md).

    python3 tools/licenses.py           write both files
    python3 tools/licenses.py --check   exit 1 if either file is out of date

What ships, and where its licence comes from:

* Rust crates linked into the `alephgrid` binary: the normal (not dev, not build) dependencies
  of alephgrid-server on the four release targets, from `cargo metadata`. The licence texts are
  the LICENSE/COPYING/NOTICE files inside each crate (the cargo registry, or vendor/ for
  IronCalc). Run `cargo fetch` first if a crate's sources are missing.
* DuckDB and the libraries bundled in its source (libduckdb-sys's duckdb.tar.gz). The tarball
  has no licence files of its own, so they are listed in DUCKDB_BUNDLED below, taken from the
  source headers. The script fails when the tarball's third_party/ folders change, so an
  upgrade gets reviewed.
* The web bundle (embedded in the binary): its production npm dependencies from
  web/package-lock.json (none today; their licence files are read from web/node_modules), the
  module-preload helper Vite inserts, and the Manrope font.

Only the Python standard library and cargo are needed. A licence outside ALLOWED stops the
script: decide, then add it here deliberately.
"""

